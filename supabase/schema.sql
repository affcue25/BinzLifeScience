-- Run this once in the Supabase dashboard: SQL Editor → New query → Run.
-- It creates the site tables, keeps them private to the service role key,
-- creates the uploads bucket for images and PDFs, and inserts the sample catalog.

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  email text not null unique,
  name text not null default '',
  password_hash text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.settings (
  key text primary key,
  value text not null
);

create table if not exists public.pages (
  key text primary key,
  content text not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.menus (
  id bigint generated by default as identity primary key,
  parent_id bigint references public.menus (id) on delete cascade,
  name text not null,
  slug text not null unique,
  description text not null default '',
  position integer not null default 0,
  visible integer not null default 1
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  menu_id bigint not null references public.menus (id) on delete cascade,
  name text not null,
  slug text not null,
  tagline text not null default '',
  description text not null default '',
  banner text not null default '',
  overview text not null default '',
  features text not null default '[]',
  pdfs text not null default '[]',
  featured integer not null default 0,
  published integer not null default 1,
  position integer not null default 0,
  created_at timestamptz not null default now(),
  unique (menu_id, slug)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text not null default '',
  subject text not null default '',
  body text not null,
  is_read integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists products_menu_id_idx on public.products (menu_id);
create index if not exists menus_parent_id_idx on public.menus (parent_id);

alter table public.users enable row level security;
alter table public.settings enable row level security;
alter table public.pages enable row level security;
alter table public.menus enable row level security;
alter table public.products enable row level security;
alter table public.messages enable row level security;

insert into storage.buckets (id, name, public)
values ('uploads', 'uploads', false)
on conflict (id) do nothing;

